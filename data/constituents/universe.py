def get_constituents(index_filter: Optional[str] = None) -> List[Constituent]:
    """Return mapped constituents, optionally filtered by index."""
    results = []
    for item in CONSTITUENTS_DATABASE:
        geo = GeographicExposure(**item["geography"])
        
        # Calculate appropriate weight based on queried index
        if index_filter == "SPX":
            w = item.get("weight_spx", 0.0)
        elif index_filter == "NDX":
            w = item.get("weight_ndx", 0.0)
        elif index_filter == "MSCIWORLD":
            w = item.get("weight_msci", 0.0)
        elif index_filter == "STOXX600":
            w = item.get("weight_stoxx", 0.0)
        elif index_filter == "AFRICA":
            w = item.get("weight_africa", 0.0)
        elif index_filter == "MIDDLE_EAST":
            w = item.get("weight_middle_east", 0.0)
        elif index_filter == "EASTERN_EUROPE":
            w = item.get("weight_eastern_europe", 0.0)
        else:
            w = (
                item.get("weight_spx", 0.0) or 
                item.get("weight_stoxx", 0.0) or 
                item.get("weight_msci", 0.0) or
                item.get("weight_africa", 0.0) or
                item.get("weight_middle_east", 0.0) or
                item.get("weight_eastern_europe", 0.0)
            )

        if index_filter and w <= 0.0001:
            continue

        c = Constituent(
            symbol=item["symbol"],
            name=item["name"],
            index=index_filter or item["index"],
            sector=item["sector"],
            sub_industry=item.get("sub_industry", ""),
            country=item.get("country", "US"),
            market_cap_bn=item["market_cap_bn"],
            weight=w,
            pe_ratio=item["pe_ratio"],
            eps_baseline=item["eps_baseline"],
            beta=item["beta"],
            dividend_yield=item["dividend_yield"],
            buyback_yield=item["buyback_yield"],
            ai_exposure_score=item["ai_exposure_score"],
            taiwan_semiconductor_dependency=item["taiwan_semiconductor_dependency"],
            energy_cost_elasticity=item["energy_cost_elasticity"],
            defense_rearmament_boost=item["defense_rearmament_boost"],
            interest_rate_duration=item["interest_rate_duration"],
            geography=geo,
            tariff_vulnerability=item["tariff_vulnerability"]
        )
        results.append(c)
    return results
